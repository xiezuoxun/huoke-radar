def _hit_list(text, words):
    """长度降序匹配；若某个词已被更长的命中词覆盖，不重复计数（避免『求推荐』+『推荐』双记）。"""
    text = str(text or "")
    got = []
    for w in sorted(words, key=len, reverse=True):
        if w and w in text:
            got.append(w)
    keep = []
    for w in got:
        if any(w != k and w in k for k in got):
            continue
        keep.append(w)
    # 保持词库原始顺序，展示更稳定
    return [w for w in words if w in keep]


def hit_words(text):
    """返回命中的意向词（高+软，最多 4 个）。"""
    got = _hit_list(text, HOT_WORDS) + _hit_list(text, SOFT_WORDS)
    out = []
    for w in HOT_WORDS + SOFT_WORDS:
        if w in got and w not in out:
            out.append(w)
        if len(out) >= 4:
            break
    return out


def is_hot(word):
    return word in HOT_WORDS


def score_of(text):
    """意向分：35 起。

    - 高意向词每个 +22（最多计 3 个）
    - 软意向词每个 +10（最多计 3 个）
    - 高+软同时命中额外 +6
    - 命中强负面词且高意向词不足 2 个 → 打 55 折（投诉帖不是线索）
    - 封顶 99

    校准依据：真实评论里「多少钱买的」「有链接吗」这类最典型的购买信号，
    通常只命中 1~2 个词，旧版（+17/+8、高门槛 85）会把它们全判成低意向。
    """
    text = str(text or "")
    hot = _hit_list(text, HOT_WORDS)
    soft = _hit_list(text, SOFT_WORDS)
    s = 35 + min(len(hot), 3) * 22 + min(len(soft), 3) * 10
    if hot and soft:
        s += 6
    if any(w in text for w in NEG_WORDS) and len(hot) < 2:
        s = int(s * 0.55)
    return max(35, min(99, s))


def level_of(score):
    """>=75 高，>=55 中，其余低。"""
    return "高" if score >= 75 else ("中" if score >= 55 else "低")



def match_industry(*texts):
    """从关键词或评论文本推断行业，未命中返回『综合行业』。"""
    blob = " ".join(str(t or "") for t in texts).lower()
    for ind in INDUSTRIES:
        for k in ind["kws"]:
            if k.lower() in blob:
                return ind["name"]
    return "综合行业"


def analyze(comment, keyword="", platform="", name=""):
    """对单条评论做完整意向分析，返回结构化结果。"""
    score = score_of(comment)
    hits = hit_words(comment)
    return {
        "name": name,
        "platform": platform,
        "comment": comment,
        "industry": match_industry(keyword, comment),
        "level": level_of(score),
        "score": score,
        "keywords": " / ".join(hits),
    }


